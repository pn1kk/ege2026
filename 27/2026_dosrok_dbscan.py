from math import dist

def dbscan(dots, eps):
    all_clusters = []

    while len(dots) > 0:
        x = dots.pop()
        new_cluster = [x]

        i = 0
        while i < len(new_cluster):
            d = new_cluster[i]
            neighbours = []

            for d2 in dots[:]:
                if dist(d[:2], d2[:2]) <= eps and d2 not in new_cluster:
                    neighbours += [d2]
                    dots.remove(d2)
            new_cluster += neighbours
            i += 1
        all_clusters += [new_cluster]
    return all_clusters

def center(cl):
    s = float('inf')
    c = cl[0]
    for d in cl:
        cur = 0
        for d2 in cl:
            cur += dist(d[:2], d2[:2])
        if cur < s:
            s = cur
            c = d
    return c

